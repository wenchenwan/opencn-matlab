function cfg = FeedoptDefaultConfig()

coder.inline("never");

tol_col_compress_deg    = 10;
tol_col_smooth_deg      = 10;

% Computation of Gauss-Legendre knots and weights for numerical integration
GaussLegendreN = 5;  % number of evaluation points
[GaussLegendreX, GaussLegendreW] = lgwt(GaussLegendreN, -1, 1); % normalized to integration interval [-1, 1]
GaussLegendreX = flipud(GaussLegendreX);

LP = struct(...
    'Type', 'LP', ...
    'EnableFindReasonInfeasibility', true,...
    'ACC_RAMP_OVER_WINDOWS', 1.0 - 1E-3,...
    'VEL_RAMP_OVER_WINDOWS', 1.0 - 1E-3,...
    'SLACK_PENALTY', 100, ...
    'USE_LINPROG', false);

cfg = struct(...
    'NumberAxis', int32( 5 ), ...
    'NCart', int32( 3 ), ...
    'NRot', int32( 2 ), ...
    'indCart', int32( [ 1, 2, 3 ]' ), ...
    'indRot', int32( [ 2,3 ]' ),...
    'indTot', int32( [ 0 ] ),...
    'NDiscr', int32( 20 ),...
    'NBreak', int32( 10 ),...
    'UseDynamicBreakpoints',false,...       % Use a variable number of breakpoints for different lengths
    'UseLinearBreakpoints',false,...        % Use a linear distribution of breakpoints (else sinspace)
    'DynamicBreakpointsDistance', 0.1,...   % Distance between two breakpoints in mm
    'NHorz', int32( 5 ),...
    'vmax', 150,...
    'amax', [20000,20000,20000,0, 20000,20000],...
    'jmax', [1500000,1500000,1500000,0,1500000,1500000] / 10,...
    'LeeSplineDegree', int32( 4 ),...
    'SplineDegree',    int32( 3 ),...
    'CutOff', 0.1,...
    'LSplit', 3.0,...
    'LSplitZero', 0.1,...
    'LThreshold', 0.3,...
    'CuspThreshold', 45,...
    'v_0', 0, 'at_0', 0,...
    'v_1', 0, 'at_1', 0,...
    'dt', 1e-4, ...
    'ZeroStartAccLimit', 0.01, ...
    'ZeroStartJerkLimit', 1, ...
    'ZeroStartVelLimit', 0.5, ...
    'source', repmat(char(0), [1, 1024]),...
    'DebugCutZero', false,...
    'Compressing', struct(...
    'Skip', false,...
    'ColTolCosLee',     cosd(tol_col_compress_deg)),...
    'ColTolCosSmooth',  cosd(tol_col_smooth_deg), ...
    'GaussLegendreN', GaussLegendreN, ...
    'GaussLegendreX', GaussLegendreX, ...
    'GaussLegendreW', GaussLegendreW, ...
    'opt', LP,...
    'LogFileName', 'logs/logs');


if ~coder.target( 'MATLAB' )
    coder.varsize( 'cfg.indCart',   StructTypeName.dimInd{ : } );
    coder.varsize( 'cfg.indRot',    StructTypeName.dimInd{ : } );
    coder.varsize( 'cfg.indTot',    StructTypeName.dimIndTot{ : } );
    coder.cstructname( LP,          StructTypeName.LPCfg );
    coder.cstructname( cfg,         StructTypeName.FeedoptCfg );
end

cfg = check_values( cfg );
end

function [ cfg ] = check_values( cfg )

% Define index
if( cfg.NCart == 0 )    % Only rotation
    cfg.indTot = cfg.indRot;
elseif( cfg.NRot == 0 ) % Only cartesian
    cfg.indTot = cfg.indCart;
else
    cfg.indTot = [ cfg.indCart; cfg.indRot ];
end

cfg.NumberAxis  = int32( length( cfg.indTot ) );
cfg.NRot        = int32( length( cfg.indRot ) );
cfg.NCart       = int32( length( cfg.indCart ) );

end
